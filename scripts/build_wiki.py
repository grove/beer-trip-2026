#!/usr/bin/env python3
"""Render the Markdown reference pages from the canonical venue records."""

import argparse
import hashlib
import json
from collections import defaultdict
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[1]
MARKER = "<!-- Generated by scripts/build_wiki.py; edit data/venues.json. -->"
REGIONS = {
    "manchester": ("Manchester, Salford and nearby suburbs", "City pubs, heritage rooms, cider specialists and selected brewery experiences."),
    "liverpool": ("Liverpool, the north coast and Wirral", "Central Liverpool and Georgian pubs, coastal excursions and distinct Wirral clusters."),
    "surroundings": ("Surrounding towns and worthwhile excursions", "Exceptional destinations that compete for an excursion day; choose a corridor rather than collecting towns."),
}
PRIORITY = {"essential": 0, "high": 1, "specialist": 2}
CIDER = {
    "documented-real": "Real cider documented; reconfirm stock",
    "reported-cider-check-qualification": "Cider reported; qualification needs checking",
    "unverified": "Real-cider offering not established",
    "none-reported": "No real cider reported by the cited evidence",
}


def cell(value):
    return str(value).replace("|", "\\|").replace("\n", " ")


def venue_link(venue, prefix="venues/"):
    return f"[{venue['name']}]({prefix}{venue['id']}.md)"


def first_sentence(text):
    # Keep the editorial summary intact; avoid truncating in the middle of a word.
    for delimiter in (". ", "! ", "? "):
        if delimiter in text:
            return text.split(delimiter, 1)[0] + delimiter[0]
    return text


def render():
    db = json.loads((ROOT / "data/venues.json").read_text())
    venues = db["venues"]
    date = db["research_date"]
    outputs = {}
    source_records = {}
    for venue in venues:
        for source in venue["sources"]:
            url = source["url"]
            if url not in source_records:
                source_records[url] = {
                    "id": "src-" + hashlib.sha256(url.encode()).hexdigest()[:12],
                    "url": url, "title": source["title"], "kind": source["kind"],
                    "checked": date, "uses": [],
                }
            source_records[url]["uses"].append({"venue_id": venue["id"], "supports": source["supports"]})

    for venue in venues:
        front = "\n".join(f"{key}: {json.dumps(venue[key], ensure_ascii=False)}" for key in (
            "id", "region", "area", "priority", "cider_status", "source_checked", "evidence_level"
        ))
        map_url = "https://www.google.com/maps/search/?api=1&query=" + quote(venue["name"] + ", " + venue["address"], safe="")
        related = [v for v in venues if v["region"] == venue["region"] and v["area"] == venue["area"] and v["id"] != venue["id"]]
        related.sort(key=lambda v: (PRIORITY[v["priority"]], v["name"].casefold()))
        lines = [
            "---", front, "---", "", MARKER, "", f"# {venue['name']}", "",
            f"[Home](../../README.md) · [Area directory](../areas/{venue['region']}.md) · [All venues](../catalogue.md)", "",
            "| Field | Detail |", "| --- | --- |",
            f"| Area | {cell(venue['area'])} |",
            f"| Priority | {venue['priority'].title()} |",
            f"| Type | {cell(venue['venue_type'])} |",
            f"| Address | {cell(venue['address'])} · [Map search]({map_url}) |",
            f"| Evidence | {venue['evidence_level']} |",
            f"| Sources checked | {venue['source_checked']} — not a live opening or stock guarantee |", "",
            "## Why visit", "", venue["why_visit"], "",
            "## Beer", "", venue["beer"], "",
            "## Cider and perry", "", f"**{CIDER[venue['cider_status']]}.** {venue['cider_note']}", "",
            "See [how cider is classified](../real-cider.md).", "",
            "## Food", "", venue["food"], "",
            "## Plan the visit", "", venue["visit_notes"], "",
            "**Getting there:** " + venue["transport"], "",
            "Check [November transport issues](../logistics.md) for date-specific disruption.", "",
            "**Tags:** " + ", ".join(venue["tags"]), "",
            "## Sources and what they establish", "",
        ]
        for source in venue["sources"]:
            sid = source_records[source["url"]]["id"]
            lines.append(f"- [{source['title']}]({source['url']}) — {source['kind']}; {source['supports']} (`{sid}`).")
        lines.extend(["", "Recommendations are editorial judgments from these sources; see [methodology](../methodology.md).", ""])
        if related:
            lines.extend(["## Also in this area", "", ", ".join(venue_link(v, "") for v in related[:7]) + ". These are area links, not an asserted walking order.", ""])
        outputs[f"wiki/venues/{venue['id']}.md"] = "\n".join(lines)

    for region, (title, intro) in REGIONS.items():
        selected = [v for v in venues if v["region"] == region]
        lines = [MARKER, "", f"# {title}", "", "[Home](../../README.md) · [Wiki index](../index.md) · [Five-day plan](../five-day-plan.md) · [Excursion choices](../excursions.md)", "", intro, "", f"**{len(selected)} selected venues. Sources checked {date}.** Priority is relative to the area's specialism; use the [shortlists](../shortlists.md) to choose across the entire trip.", ""]
        areas = defaultdict(list)
        for venue in selected:
            areas[venue.get("cluster", venue["area"])].append(venue)
        for area in sorted(areas):
            lines.extend([f"## {area}", "", "| Venue | Priority | Reason to go | Cider evidence |", "| --- | --- | --- | --- |"])
            for venue in sorted(areas[area], key=lambda v: (PRIORITY[v["priority"]], v["name"].casefold())):
                lines.append(f"| {venue_link(venue, '../venues/')} | {venue['priority']} | {cell(first_sentence(venue['why_visit']))} | {CIDER[venue['cider_status']]} |")
            lines.append("")
        outputs[f"wiki/areas/{region}.md"] = "\n".join(lines)

    lines = [MARKER, "", "# Complete venue catalogue", "", "[Home](../README.md) · [Shortlists](shortlists.md) · [Cider guide](real-cider.md) · [Source register](sources.md)", "", f"**{len(venues)} selected venues**, researched {date}. Every name links to beer, cider, food, transport, practical qualifications and evidence. This is a curated longlist, not a claim to contain every good pub in the region.", "", "| Venue | Region / area | Priority | Cider evidence |", "| --- | --- | --- | --- |"]
    for venue in sorted(venues, key=lambda v: v["name"].casefold()):
        lines.append(f"| {venue_link(venue)} | {cell(venue['region'] + ' / ' + venue['area'])} | {venue['priority']} | {CIDER[venue['cider_status']]} |")
    outputs["wiki/catalogue.md"] = "\n".join(lines) + "\n"

    lines = [MARKER, "", "# Venue source register", "", "[Home](../README.md) · [Methodology](methodology.md) · [Catalogue](catalogue.md)", "", f"**{len(source_records)} distinct venue-source URLs.** Checked {date}; source publication and update dates may be older. The source's precise support is recorded on each venue page and in [data/sources.json](../data/sources.json). General definitions, transport and event sources are cited separately on their relevant planning pages.", "", "| Source ID | Source | Type | Used for |", "| --- | --- | --- | --- |"]
    by_id = {v["id"]: v for v in venues}
    for source in sorted(source_records.values(), key=lambda s: (s["kind"], s["title"].casefold(), s["url"])):
        uses = ", ".join(venue_link(by_id[use["venue_id"]]) for use in source["uses"])
        lines.append(f"| `{source['id']}` | [{cell(source['title'])}]({source['url']}) | {source['kind']} | {uses} |")
    outputs["wiki/sources.md"] = "\n".join(lines) + "\n"
    outputs["data/sources.json"] = json.dumps({"schema_version": 1, "research_date": date, "sources": sorted(source_records.values(), key=lambda s: s["id"])}, ensure_ascii=False, indent=2) + "\n"

    lines = ["# Manchester and Liverpool Beer Trip 2026", "", "> Source-backed wiki for two experienced beer travellers on a five-day November 2026 trip. Priorities: real ale, real cider/perry, traditional and spectacular pubs, worthwhile food. Read uncertainty notes before recommending a visit.", "", f"Research date: {date}. Venue count: {len(venues)}. Relative links resolve from this repository root. Do not infer current stock, opening or reservations from this snapshot.", "", "## Start here", "", "- [README](README.md): navigation and trip priorities.", "- [Wiki index](wiki/index.md): topic map.", "- [Methodology](wiki/methodology.md): scope, evidence hierarchy and limitations.", "- [Cider guide](wiki/real-cider.md): evidence states and product qualification.", "- [Shortlists](wiki/shortlists.md): strongest matches by interest.", "- [Five-day plan](wiki/five-day-plan.md): modular route with substitutions.", "- [Excursions](wiki/excursions.md): time and interest tradeoffs.", "- [November events](wiki/november-events.md): advertised 2026 opportunities.", "- [Logistics](wiki/logistics.md): confirmed November transport cautions.", "- [Changes and exclusions](wiki/changes-and-exclusions.md): closures and conflicting evidence.", "- [Research log](wiki/log.md): material changes and follow-up work.", "", "## Canonical data", "", "- [Venue data](data/venues.json): canonical records, stable IDs, sources and qualifications.", "- [Source register](data/sources.json): source-to-venue provenance.", "- [Events](data/events.json): advertised dates and caveats.", "- [Data guide](data/README.md): schema and update workflow.", "- [Catalogue](wiki/catalogue.md): all selected venues.", "", "## Area directories", ""]
    for region, (title, _) in REGIONS.items():
        lines.append(f"- [{title}](wiki/areas/{region}.md)")
    lines.extend(["", "## Venue pages", ""])
    for venue in sorted(venues, key=lambda v: (v["region"], v["name"].casefold())):
        lines.append(f"- {venue_link(venue, 'wiki/venues/')}: {venue['area']}; {venue['priority']}; cider={venue['cider_status']}.")
    outputs["llms.txt"] = "\n".join(lines) + "\n"
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Report drift without writing files")
    args = parser.parse_args()
    outputs = render()
    changed = []
    for relative, content in outputs.items():
        path = ROOT / relative
        if not path.exists() or path.read_text() != content:
            changed.append(relative)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content)
    stale = [p for p in (ROOT / "wiki/venues").glob("*.md") if str(p.relative_to(ROOT)) not in outputs and MARKER in p.read_text()]
    changed.extend(str(p.relative_to(ROOT)) for p in stale)
    if not args.check:
        for path in stale:
            path.unlink()
    if args.check and changed:
        raise SystemExit("Generated files need rebuilding:\n" + "\n".join(changed))
    print(f"{'Checked' if args.check else 'Rendered'} {len(outputs)} generated files; {len(changed)} {'out of date' if args.check else 'changed'}.")


if __name__ == "__main__":
    main()
