#!/usr/bin/env python3
"""Render the opinionated complete venue ranking from canonical JSON records."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARKER = "<!-- Generated by scripts/build_rankings.py; edit data/rankings.json or data/venues.json. -->"
TOP_REASONS = {
  "marble-arch": "Exceptional Marble cask, real cider, Victorian tiling and proper food; Tuesday closure makes timing essential.",
  "ship-and-mitre": "Liverpool’s most complete breadth of real ale, world beer, cider and a traditional pub atmosphere, with food.",
  "petersgate-tap-stockport": "Probably the best compact Stockport blend of changing cask and serious real cider/perry.",
  "fox-and-pine-oldham": "Top-tier dark cask selection and multiple real ciders/perries; Oldham’s 2026 branch winner.",
  "that-beer-place-chester": "Chester’s standout specialist cider/perry collection and interesting beer; a full excursion.",
  "turks-head-st-helens": "St Helens landmark with cask and cider depth, food and national 2026 POTY-finalist recognition.",
  "roscoe-head": "Small-room independent cask ideal; the ultimate Liverpool traditional-local anchor.",
  "lion-tavern": "Original historic pub detail, cask, cider and exceptional atmosphere in a small city-centre space.",
  "crown-and-kettle": "An extraordinary old ceiling with changing cask and documented real cider.",
  "cafe-beermoth": "2026 Central Manchester Pub of the Year; broad cask and remarkable bottle selection.",
  "philharmonic-dining-rooms": "Liverpool’s most spectacular heritage room, with cask and meals; less cider-led.",
  "stalybridge-buffet-bar": "Victorian railway buffet, a genuine one-off pub experience, cask and cider.",
  "coop-crosby": "2026 Liverpool branch Pub of the Year; serious changing cask and cider in Crosby.",
  "arden-arms-stockport": "A model of Stockport old pub rooms, Robinsons cask and meals; cider not established.",
  "our-gracies-rochdale": "2026 Rochdale cider winner, a highly worthwhile specialist cider/perry and cask detour."
}
REGION_NAMES = {"manchester": "Manchester and Salford", "liverpool": "Liverpool and Wirral", "surroundings": "Surrounding towns"}

def link(v):
    return f"[{v['name']}](venues/{v['id']}.md)"

def cider(v):
    status = v["cider_status"]
    return {
        "documented-real": "Documented (check stock)",
        "reported-cider-check-qualification": "Reported, unqualified",
        "none-reported": "None evidenced",
        "unverified": "Unverified",
    }[status]

def row(v, rank):
    return f"| {rank} | {link(v)} | {v['area']} | {cider(v)} |"

def render_rankings():
    data = json.loads((ROOT / "data/rankings.json").read_text())
    db = json.loads((ROOT / "data/venues.json").read_text())
    by_id = {v["id"]: v for v in db["venues"]}
    ids = data["ranking_ids"]
    if len(ids) != len(by_id) or set(ids) != set(by_id) or len(ids) != len(set(ids)):
        raise ValueError("Ranked IDs must exactly cover unique canonical venue IDs")
    ranks = {identifier: i + 1 for i, identifier in enumerate(ids)}
    venues = [by_id[x] for x in ids]
    l = [
        MARKER, "", "# Ranked beer destinations — Manchester, Liverpool and the surrounding area", "",
        "[Home](../README.md) · [Dated itinerary](five-day-plan.md) · [Cider guide](real-cider.md) · [All venue profiles](catalogue.md)", "",
        f"**{len(ids)} ranked choices, strongest overall first.** This is an *editorial relevance ranking*, not a firsthand tasting inspection, star rating or a statement of which tap is serving the best-conditioned pint today. It reflects evidenced real-ale/cider depth, distinctive interiors and atmosphere, beer experiences, 2026 awards, food and visit value. A highly ranked excursion outside the two cities may be a poor *time fit* for these particular 9–14 November dates. Use the [dated schedule](five-day-plan.md) to make a realistic selection.", "",
        "## The fifteen highest priorities", "",
        "| Rank | Venue | Why it earns a top slot |", "| ---: | --- | --- |",
    ]
    for identifier in ids[:15]:
        l.append(f"| {ranks[identifier]} | {link(by_id[identifier])} | {TOP_REASONS[identifier]} |")
    l.extend(["", "## Full ranking, 1–158", "",
        "Every venue below is individually curated; a lower rank is not a bad pub. Cider classification is based on source evidence, not a live stock board. **Documented** sometimes means occasional only, as the linked venue profile explains.", "",
        "| Overall rank | Venue | Area | Real-cider evidence |", "| ---: | --- | --- | --- |"])
    l.extend(row(v, ranks[v["id"]]) for v in venues)
    l.extend(["", "## Rankings within each region", ""])
    for region in ("manchester", "liverpool", "surroundings"):
        l.extend([f"### {REGION_NAMES[region]}", "", "| Overall rank | Venue | Area | Real-cider evidence |", "| ---: | --- | --- | --- |"])
        l.extend(row(v, ranks[v["id"]]) for v in venues if v["region"] == region)
        l.append("")
    l.extend(["## How to use these positions", "",
        "The top section is judgment-led rather than an arithmetic league table. For the remaining records, the stable order reflects existing essential/high/specialist curation, evidence of cask and real cider, specialist cider/perry, heritage, dark styles, meal options and practical travel. Scores are intentionally *not published* because their numerical precision would be misleading. A real-cider badge alone does not prove a large cider list, and some documented cider is occasional.", "",
        "For **Manchester days**, put Marble Arch, Crown & Kettle, Café Beermoth, Smithfield, City Arms, Peveril and Britons Protection ahead of another generic taproom. For **Liverpool days**, put Ship & Mitre, Roscoe Head, Lion, Philharmonic, Peter Kavanagh’s and The Vines ahead of a broad keg-only tasting. For **excursions**, choose **Stockport** for variety and easy integration, or **Oldham, St Helens, Chester, Crosby and Rochdale** when their particular cider/ale experience warrants the train time.", "",
        "Read the [flight-aware schedule](five-day-plan.md), [November events](november-events.md), and [source methodology](methodology.md) before choosing. Times, beer lineups and the identity of qualifying cider are not guaranteed by this static ranking.", ""])
    return "\n".join(l) + "\n"

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare generated ranking with committed Markdown")
    args = parser.parse_args()
    path = ROOT / "wiki/rankings.md"
    text = render_rankings()
    if args.check:
        if not path.exists() or path.read_text() != text:
            raise SystemExit("Ranking out of date: run python3 scripts/build_rankings.py")
        print("Ranking up to date:", len(json.loads((ROOT / "data/rankings.json").read_text())["ranking_ids"]), "venues")
    else:
        path.write_text(text)
        print("Rendered ranking:", path)

if __name__ == "__main__":
    main()
